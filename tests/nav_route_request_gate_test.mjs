import assert from 'node:assert/strict';
import {NavRouteRequestGate} from '../sim/nav_route_request_gate.mjs';
const gate=new NavRouteRequestGate();
const a=gate.begin('foot:one');
assert.equal(gate.owns(a),true);
assert.equal(a.signal.aborted,false);
const b=gate.begin('foot:two');
assert.equal(a.signal.aborted,true,'new destination must abort previous fetch');
assert.equal(gate.owns(a),false,'previous reply must never be committed');
assert.equal(gate.finish(a),false,'previous finally must not clear new pending request');
assert.equal(gate.owns(b),true);
assert.equal(gate.finish(b),true);
assert.equal(gate.owns(b),false);
const c=gate.begin('car:two');
gate.cancel();
assert.equal(c.signal.aborted,true,'switching profile invalidates the in-flight fetch');
assert.equal(gate.finish(c),false);
const d=gate.begin('foot:three');
d.controller.abort();
assert.equal(gate.owns(d),false,'timed-out fetch cannot update route');
assert.equal(gate.finish(d),true,'current timeout should unlock route requests');
console.log('Navigation request epochs and abort: pass');
