import assert from "node:assert/strict";
import {VOICE_KEY_PTT,VOICE_KEY_MUTE,VOICE_PAD_PTT,VOICE_PAD_MUTE,nextVoicePadInput} from "../sim/voice_control_bindings.mjs";
assert.equal(VOICE_KEY_PTT,"KeyH");assert.equal(VOICE_KEY_MUTE,"KeyK");
assert.equal(VOICE_PAD_PTT,11);assert.equal(VOICE_PAD_MUTE,3);
let s={y:false,latched:false};
s=nextVoicePadInput(s,{r3:true,allowed:true});assert.equal(s.talk,true);assert.equal(s.mute,false);
s=nextVoicePadInput(s,{r3:true,y:true,allowed:true});
assert.equal(s.talk,false,"PTT must stop while muting");
assert.equal(s.mute,true,"first R3+Y edge toggles mute");
assert.equal(s.suppressWeapon,true,"mute chord may never switch the weapon");
s=nextVoicePadInput(s,{r3:true,y:true,allowed:true});
assert.equal(s.mute,false,"holding Y must not repeatedly toggle mute");
assert.equal(s.talk,false,"do not reopen PTT while mute chord is latched");
s=nextVoicePadInput(s,{r3:true,y:false,allowed:true});assert.equal(s.talk,false);
s=nextVoicePadInput(s,{r3:false,y:false,allowed:true});assert.equal(s.talk,false);
s=nextVoicePadInput(s,{r3:true,allowed:true});assert.equal(s.talk,true,"next R3 hold works after release");
s=nextVoicePadInput(s,{r3:true,allowed:false});assert.equal(s.talk,false,"menu/map/death must stop PTT");
s=nextVoicePadInput(s,{r3:false,allowed:true});
assert.equal(s.talk,false);
console.log("Voice controller: R3 PTT hold/release, R3+Y mute latch, no weapon swap, menu release: pass");
