import assert from "node:assert/strict";
import {VOICE_KEY_PTT,VOICE_KEY_MUTE,VOICE_PAD_PTT,VOICE_PAD_MUTE,nextVoicePadInput} from "../sim/voice_control_bindings.mjs";
assert.equal(VOICE_KEY_PTT,"KeyH");assert.equal(VOICE_KEY_MUTE,"KeyK");
assert.equal(VOICE_PAD_PTT,11);assert.equal(VOICE_PAD_MUTE,3);
let s={r3:false,y:false,latched:false};
s=nextVoicePadInput(s,{r3:true,allowed:true});
assert.equal(s.micToggle,false,"press alone does not toggle until release");
s=nextVoicePadInput(s,{r3:false,allowed:true});
assert.equal(s.micToggle,true,"R3 tap toggles always-on mic exactly once on release");
s=nextVoicePadInput(s,{r3:false,allowed:true});
assert.equal(s.micToggle,false);
s=nextVoicePadInput(s,{r3:true,allowed:true});
s=nextVoicePadInput(s,{r3:true,y:true,allowed:true});
assert.equal(s.mute,true,"R3+Y toggles speaker mute");
assert.equal(s.suppressWeapon,true,"mute chord must never switch weapon");
s=nextVoicePadInput(s,{r3:true,y:true,allowed:true});
assert.equal(s.mute,false,"holding Y must not repeatedly toggle");
s=nextVoicePadInput(s,{r3:false,y:false,allowed:true});
assert.equal(s.micToggle,false,"R3+Y must NOT toggle the microphone on release");
s=nextVoicePadInput(s,{r3:true,allowed:true});
s=nextVoicePadInput(s,{r3:false,allowed:false});
assert.equal(s.micToggle,false,"menu/map prevents mic toggle on release");
console.log("Xbox mic toggle: single R3 tap; R3+Y exclusive mute; no weapon swap: pass");
