import assert from 'node:assert/strict';
import {sampleElevationField,setElevationGrid} from '../sim/terrain_elevation.mjs';
import {setRoadCorridors,staticGroundHeightAt} from '../sim/terrain_craters.mjs';
const opts={x0:-250,y0:-250,n:101,unproject:(x,y)=>[x,y],yieldFrame:async()=>{}};
const plane=(x,y)=>100+x*.02+y*.01;
const full=await sampleElevationField({...opts,sample:plane});
assert.ok(full instanceof Float32Array);
assert.ok(Math.abs(full[50*101+50]-100)<1e-4,'a genuine slope retains its height');
assert.equal(await sampleElevationField({...opts,sample:(x,y)=>x>=0&&y>=0?null:plane(x,y)}),null,'one missing DEM quadrant must reject the whole scan, not fabricate plateaus');
assert.equal(await sampleElevationField({...opts,sample:()=>NaN}),null);
let active=true;
assert.equal(await sampleElevationField({...opts,sample:plane,current:()=>active,yieldFrame:async()=>{active=false;}}),null,'world origin change during an asynchronous scan rejects stale heights');
const grid=z=>({x0:-250,y0:-250,n:101,step:5,cx:0,cy:0,h:new Float32Array(101*101).fill(z)});
setElevationGrid(grid(0));
setRoadCorridors([{pts:[[-100,0],[100,0]],w:12}]);
assert.equal(staticGroundHeightAt(0,0),0);
setElevationGrid(grid(30));
assert.equal(staticGroundHeightAt(0,0),30,'road center must follow a newly loaded DEM instead of retaining flat pre-load heights');
assert.equal(staticGroundHeightAt(0,50),30,'road and surrounding terrain share the new height');
assert.equal(setRoadCorridors([{pts:[[-100,0],[0,20],[100,0]],w:12}]),true,'changed middle vertices must refresh road corridors');
setRoadCorridors([]);setElevationGrid(null);
console.log('Complete DEM / stale scan / road refresh: pass');
